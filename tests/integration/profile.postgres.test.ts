import { afterAll, beforeAll, expect, test } from 'vitest';
import { emptyProfile } from '../../packages/contracts/src';
import { PrismaProjectRepository } from '../../apps/api/src/projects/prisma-repository';
import { testDatabase } from '../support/postgres';
import { analysisResult } from '../support/analysis';
let fixture: Awaited<ReturnType<typeof testDatabase>>;
beforeAll(async () => { fixture = await testDatabase(); }, 60_000);
afterAll(async () => { if (fixture) await fixture.stop(); });
test('only one simultaneous PATCH wins and reanalysis preserves confirmed Profile', async () => {
  const db = fixture.db;
  await db.user.create({ data: { id: 'owner', name: 'Owner', email: 'owner@example.invalid' } });
  const repository = new PrismaProjectRepository(db);
  const project = await repository.create('owner', '경합');
  const first = { ...emptyProfile(), database: 'PostgreSQL' };
  const second = { ...emptyProfile(), database: 'SQLite' };
  const results = await Promise.allSettled([repository.saveProfile('owner', project.id, { expectedVersion: 1, profile: first }), repository.saveProfile('owner', project.id, { expectedVersion: 1, profile: second })]);
  expect(results.filter(r => r.status === 'fulfilled')).toHaveLength(1);
  const failed = results.find(r => r.status === 'rejected');
  expect(failed?.status === 'rejected' && failed.reason.code).toBe('VERSION_CONFLICT');
  const saved = await repository.findOwned('owner', project.id);
  expect(saved?.version).toBe(2);
  expect(await db.profileAudit.count({ where: { projectId: project.id } })).toBe(1);
  const snapshot = saved!.confirmedProfile;
  await db.draft.create({ data: { projectId: project.id, result: analysisResult() as object } });
  const reopened = await new PrismaProjectRepository(db).findOwned('owner', project.id);
  expect(reopened?.confirmedProfile).toEqual(snapshot);
  expect(reopened?.draft?.result.profile.backend).toEqual(['Express.js']);
  await expect(repository.saveProfile('foreign', project.id, { expectedVersion: 2, profile: first })).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND' });
});
