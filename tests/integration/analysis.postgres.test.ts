test('durable local queue waits when worker is off, then completes without browser polling', async () => {
  const s = await setup('queue');
  const record = await s.repository.start(s.user.id, s.project.id, s.grant.uploadId, 'nvidia', new Date());
  const analyze = vi.fn(async () => analysisResult(record.id));
  const cleanup = new CleanupService(s.uploads, s.store);
  const worker = new AnalysisWorker(s.repository, { analyze }, async id => { await cleanup.cleanupUpload(id, true); });
  const outbox = new OutboxDispatcher(s.db, new LocalQueue(), worker, s.repository, cleanup);
  await outbox.publishTarget(record.id);
  expect((await s.repository.getOwned(s.user.id, s.project.id, record.id))?.status).toBe('QUEUED');
  expect(analyze).not.toHaveBeenCalled();
  await new LocalWorkerLoop(outbox).tick();
  expect((await s.repository.getOwned(s.user.id, s.project.id, record.id))?.status).toBe('SUCCEEDED');
  const message = (await s.db.jobOutbox.findFirstOrThrow({ where: { targetId: record.id, kind: 'analyze' } }));
  await outbox.process({ outboxId: message.id, kind: message.kind, targetId: message.targetId });
  expect(analyze).toHaveBeenCalledTimes(1);
  s.store.dispose();
});
test('HTTP upload/analysis enforce sessions, ownership and reopen persisted active attempt', async () => {
  const s = await setup('http'); const origin = 'http://localhost:3000';
  const cleanup = new CleanupService(s.uploads, s.store);
  const analysis = new AnalysisService(s.repository, s.service, async () => {}, cleanup);
  const app = createApp({ webOrigin: origin, projects: s.projects, uploads: s.service, analysis, session: async headers => headers.authorization === 'Bearer test-owner' ? { id: s.user.id, name: 'Test owner' } : null });
  const path = `/api/projects/${s.project.id}`;
  expect((await request(app).post(`${path}/analysis`).set('Origin', origin).set('x-user-id', s.user.id).send({ input: { kind: 'upload', uploadId: s.grant.uploadId }, provider: 'solar' })).status).toBe(401);
  const grant = await request(app).post(`${path}/uploads`).set('Authorization', 'Bearer test-owner').set('Origin', origin).send({ kind: 'text', size: 5, contentType: 'text/plain' });
  expect(grant.status).toBe(201);
  expect((await request(app).put(grant.body.uploadUrl).set('Authorization', 'Bearer test-owner').set('Origin', origin).set('Content-Type', 'text/plain').send('Hello')).status).toBe(204);
  expect((await request(app).post(`${path}/analysis`).set('Authorization', 'Bearer test-owner').set('Origin', origin).send({ input: { kind: 'upload', uploadId: 'stolen' }, provider: 'solar' })).status).toBe(404);
  const started = await request(app).post(`${path}/analysis`).set('Authorization', 'Bearer test-owner').set('Origin', origin).send({ input: { kind: 'upload', uploadId: s.grant.uploadId }, provider: 'solar' });
  expect(started.status).toBe(202); expect(started.body.status).toBe('QUEUED');
  const reopened = await request(app).get(path).set('Authorization', 'Bearer test-owner');
  expect(reopened.body.activeAttempt.id).toBe(started.body.id);
  expect((await request(app).get(`${path}/analysis/${started.body.id}`).set('Authorization', 'Bearer test-owner')).body.status).toBe('QUEUED');
  expect((await request(app).post(`${path}/analysis/${started.body.id}/cancel`).set('Authorization', 'Bearer test-owner').set('Origin', origin).send({})).body.status).toBe('CANCELLED');
  s.store.dispose();
});
test('internal input requires token and live lease, and returns no public cloud proxy', async () => {
  const s = await setup('internal'); const record = await s.repository.start(s.user.id, s.project.id, s.grant.uploadId, 'nvidia', new Date());
  const claimed = await s.repository.claim(record.id, new Date());
  const token = 'test-only-internal-token'.repeat(2);
  const app = createApp({ webOrigin: 'http://localhost:3000', projects: s.projects, session: async () => null, internal: internalRoutes({ db: s.db, token, inputs: s.store, budget: new BudgetService(s.db, 20_000_000, 44_000) }) });
  const url = `/internal/v1/inputs/${s.grant.uploadId}`;
  expect((await request(app).get(url).query({ attemptId: record.id, leaseId: claimed!.leaseId })).status).toBe(403);
  expect((await request(app).get(url).set('Authorization', `Bearer ${token}`).query({ attemptId: record.id, leaseId: 'forged' })).status).toBe(403);
  const metadata = await request(app).get(`${url}/metadata`).set('Authorization', `Bearer ${token}`).query({ attemptId: record.id, leaseId: claimed!.leaseId });
  expect(metadata.status).toBe(200); expect(metadata.body.metadata.size).toBe(19); expect(JSON.stringify(metadata.body)).not.toContain('Express.js');
  const bytes = await request(app).get(url).set('Authorization', `Bearer ${token}`).query({ attemptId: record.id, leaseId: claimed!.leaseId });
  expect(bytes.status).toBe(200); expect(bytes.headers['cache-control']).toBe('no-store');
  expect(Buffer.from(bytes.body).toString('utf8')).toBe('Backend: Express.js');
  await s.repository.cancelOwned(s.user.id, s.project.id, record.id, new Date());
  expect((await request(app).get(url).set('Authorization', `Bearer ${token}`).query({ attemptId: record.id, leaseId: claimed!.leaseId })).status).toBe(403);
  s.store.dispose();
});
