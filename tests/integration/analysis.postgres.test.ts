async function setup(label: string) {
  const db = fixture.db; const projects = new PrismaProjectRepository(db);
  const user = await db.user.create({ data: { id: label, name: label, email: `${label}@example.invalid` } });
  const project = await projects.create(user.id, label); const uploads = new PrismaUploadRepository(db); const store = new LocalInputStore();
  const service = new UploadService(store, uploads, async (owner, id) => !!await projects.findOwned(owner, id), async () => {});
  const grant = await service.createUpload(user.id, project.id, { kind: 'text', size: 19, contentType: 'text/plain' });
  await service.completeLocalUpload(user.id, project.id, grant.uploadId, new TextEncoder().encode('Backend: Express.js'));
  return { db, projects, user, project, uploads, store, grant, repository: new PrismaAttemptRepository(db), service };
}
test('limits global/user/project concurrency atomically and stores raw-free outbox', async () => {
  const a = await setup('slot-a'), b = await setup('slot-b'), c = await setup('slot-c');
  const now = new Date();
  const outcomes = await Promise.allSettled([a, b, c].map(s => s.repository.start(s.user.id, s.project.id, s.grant.uploadId, 'nvidia', now)));
  expect(outcomes.filter(r => r.status === 'fulfilled')).toHaveLength(2);
  expect(outcomes.find(r => r.status === 'rejected')).toMatchObject({ reason: { code: 'GLOBAL_ANALYSIS_LIMIT' } });
  const active = outcomes.filter(r => r.status === 'fulfilled').map(r => r.value);
  const one = active[0]!;
  await expect(a.repository.start(one.ownerId, one.projectId, one.inputRef.uploadId, 'nvidia', now)).rejects.toMatchObject({ code: 'ANALYSIS_ALREADY_RUNNING' });
  const anotherProject = await a.projects.create(one.ownerId, 'Other owned project');
  await expect(a.repository.start(one.ownerId, anotherProject.id, c.grant.uploadId, 'nvidia', now)).rejects.toMatchObject({ code: 'USER_ANALYSIS_LIMIT' });
  const outbox = await a.db.jobOutbox.findMany();
  expect(outbox.filter(j => j.kind === 'expire')).toHaveLength(2);
  expect(JSON.stringify(outbox)).not.toContain('Express.js');
  expect(await a.db.analysisAttempt.count({ where: { status: 'QUEUED' } })).toBe(2);
  for (const record of active) await a.repository.cancelOwned(record.ownerId, record.projectId, record.id, new Date());
  for (const s of [a, b, c]) s.store.dispose();
});

test('analysis stays valid beyond 60 seconds and rejects results at the 180 second boundary', async () => {
  const s = await setup('long-deadline'); const now = new Date();
  const record = await s.repository.start(s.user.id, s.project.id, s.grant.uploadId, 'nvidia', now);
  expect(record.deadline.getTime() - now.getTime()).toBe(180_000);
  expect((await s.db.jobOutbox.findFirstOrThrow({ where: { targetId: record.id, kind: 'expire' } })).dueAt).toEqual(record.deadline);
  await s.repository.expire(record.id, new Date(now.getTime() + 60_001));
  const claimed = await s.repository.claim(record.id, new Date(now.getTime() + 90_000));
  expect(claimed?.status).toBe('PROCESSING');
  expect(await s.repository.finish(record.id, claimed!.leaseId!, analysisResult(record.id), new Date(now.getTime() + 179_999))).toBe(true);
  const late = await setup('long-deadline-late');
  const second = await late.repository.start(late.user.id, late.project.id, late.grant.uploadId, 'nvidia', now);
  const lease = await late.repository.claim(second.id, now);
  expect(await late.repository.finish(second.id, lease!.leaseId!, analysisResult(second.id), new Date(now.getTime() + 180_000))).toBe(false);
  await late.repository.expire(second.id, new Date(now.getTime() + 180_000));
  expect((await late.repository.getOwned(late.user.id, late.project.id, second.id))?.errorCode).toBe('ANALYSIS_TIMEOUT');
  s.store.dispose(); late.store.dispose();
});
test('duplicate worker produces one persisted draft, preserves confirmed Profile, and deletes raw input', async () => {
  const s = await setup('worker');
  const confirmed = await s.projects.saveProfile(s.user.id, s.project.id, { expectedVersion: 1, profile: { ...emptyProfile(), database: 'PostgreSQL' } });
  const record = await s.repository.start(s.user.id, s.project.id, s.grant.uploadId, 'nvidia', new Date());
  const analyze = vi.fn(async () => analysisResult(record.id));
  const cleanup = new CleanupService(s.uploads, s.store);
  const worker = new AnalysisWorker(s.repository, { analyze }, async id => { await cleanup.cleanupUpload(id, true); });
  await Promise.all([worker.processAttempt(record.id), worker.processAttempt(record.id)]);
  expect(analyze).toHaveBeenCalledTimes(1);
  expect((await s.repository.getOwned(s.user.id, s.project.id, record.id))?.status).toBe('SUCCEEDED');
  expect(await s.db.draft.count({ where: { attemptId: record.id } })).toBe(1);
  expect((await s.projects.findOwned(s.user.id, s.project.id))?.confirmedProfile).toEqual(confirmed.confirmedProfile);
  await expect(s.store.read(record.inputRef)).rejects.toThrow('INPUT_UNAVAILABLE');
  s.store.dispose();
});
