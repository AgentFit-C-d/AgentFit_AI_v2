test('exposes authenticated profiles with 64KiB raw-body limits and project deletion cascades', async () => {
  const project = await fixture.db.project.create({ data: { ownerId: 'rec-owner', name: '라우트' } });
  const dependencies = { webOrigin: 'http://localhost:3000', projects: new PrismaProjectRepository(fixture.db), profiles: new ProfileRepository(fixture.db), session: async () => ({ id: 'rec-owner', name: 'Owner', image: null }) };
  const app = createApp(dependencies);
  const path = `/api/projects/${project.id}/developer-profile`;
  const saved = await request(app).put(path).set('Origin', dependencies.webOrigin).send({ expectedVersion: 0, data: developer });
  expect(saved.status).toBe(201);
  expect(saved.body.profile).toMatchObject({ version: 1, source: 'USER_DECLARED' });
  const bad = await request(app).put(path).set('Origin', dependencies.webOrigin).send({ expectedVersion: 1, data: developer, source: 'INSPECTED' });
  expect(bad.status).toBe(422);
  const large = await request(app).put(path).set('Origin', dependencies.webOrigin).set('Content-Type', 'application/json').send(' '.repeat(65537) + JSON.stringify({ expectedVersion: 1, data: developer }));
  expect(large.status).toBe(413);
  const denied = await request(app).put(path).set('Origin', 'https://evil.invalid').send({ expectedVersion: 1, data: developer });
  expect(denied.status).toBe(403);
  const anonDeps = { ...dependencies, session: async () => null };
  expect((await request(createApp(anonDeps)).get(path)).status).toBe(401);
  await fixture.db.project.delete({ where: { id: project.id } });
  expect(await fixture.db.developerProfile.count({ where: { projectId: project.id } })).toBe(0);
});
test('records deterministic recommendations, rejects stale bases and invalidates after profile or Catalog updates', async () => {
  const db = fixture.db;
  const project = await db.project.create({ data: { ownerId: 'rec-owner', name: '추천 기준' } });
  const profiles = new ProfileRepository(db);
  let catalog = loadCatalog();
  const service = new RecommendationService(db, () => catalog);
  await expect(service.create('rec-owner', project.id, { expectedVersions: { project: 1, developer: 0, environment: 0 } })).rejects.toMatchObject({ code: 'PROFILE_CONFIRMATION_REQUIRED', status: 422 });
  await new PrismaProjectRepository(db).saveProfile('rec-owner', project.id, { expectedVersion: 1, profile: { ...emptyProfile(), frontend: ['React'], backend: [] } });
  await profiles.putDeveloper('rec-owner', project.id, { expectedVersion: 0, data: developer });
  await profiles.putEnvironment('rec-owner', project.id, { expectedVersion: 0, data: environment });
  const input = { expectedVersions: { project: 2, developer: 1, environment: 1 } };
  const created = await service.create('rec-owner', project.id, input);
  expect(created).toMatchObject({ validity: 'CURRENT', status: 'RECOMMENDED', basis: { projectVersion: 2, developerVersion: 1, environmentVersion: 1, catalogRevision: catalog.revision } });
  expect(created.items.filter(item => item.required).map(item => item.catalogItemId)).toEqual(['vercel-labs-vercel-react-best-practices']);
  expect(created.items.filter(item => !item.required).map(item => item.catalogItemId).sort()).toEqual(['obra-systematic-debugging', 'obra-test-driven-development', 'obra-verification-before-completion', 'obra-writing-plans']);
  const dependencies = { webOrigin: 'http://localhost:3000', projects: new PrismaProjectRepository(db), profiles, recommendations: service, session: async () => ({ id: 'rec-owner', name: 'Owner', image: null }) };
  const app = createApp(dependencies);
  const response = await request(app).post(`/api/projects/${project.id}/recommendations`).set('Origin', dependencies.webOrigin).send(input);
  expect(response.status).toBe(201);
  expect(response.body.recommendation.status).toBe('RECOMMENDED');
  expect((await request(app).get(`/api/projects/${project.id}/recommendations/latest`)).body.recommendation.id).toBe(response.body.recommendation.id);
  expect((await service.latest('rec-owner', project.id))?.id).toBe(response.body.recommendation.id);
  catalog = { ...catalog, revision: 'changed-revision' };
  expect((await service.latest('rec-owner', project.id))?.validity).toBe('STALE');
  catalog = loadCatalog();
  await profiles.putDeveloper('rec-owner', project.id, { expectedVersion: 1, data: developer });
  await expect(service.create('rec-owner', project.id, input)).rejects.toMatchObject({ code: 'VERSION_CONFLICT', status: 409 });
  expect((await service.latest('rec-owner', project.id))?.validity).toBe('STALE');
  expect(await db.recommendation.count({ where: { projectId: project.id } })).toBe(2);
  await expect(service.latest('foreign', project.id)).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND', status: 404 });
  await db.project.update({ where: { id: project.id }, data: { deletingAt: new Date() } });
  await expect(service.create('rec-owner', project.id, { expectedVersions: { project: 2, developer: 2, environment: 1 } })).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND' });
  await db.project.delete({ where: { id: project.id } });
  expect(await db.recommendation.count({ where: { projectId: project.id } })).toBe(0);
});
