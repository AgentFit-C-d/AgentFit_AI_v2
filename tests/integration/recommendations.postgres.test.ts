let fixture: Awaited<ReturnType<typeof testDatabase>>;
beforeAll(async () => { fixture = await testDatabase(); await fixture.db.user.create({ data: { id: 'rec-owner', name: 'Owner', email: 'rec@example.invalid' } }); }, 60_000);
afterAll(async () => { if (fixture) await fixture.stop(); });
const developer = { role: 'FULL_STACK', responsibilities: ['문서 참조'], experienceLevel: null };
const environment = { os: { family: 'WINDOWS', version: '11' }, client: { id: 'codex-desktop', version: '26.930.4958.0' }, runtimes: [], installedComponents: [], configurationKnowledge: 'USER_SAYS_EMPTY', authenticationReadiness: [] };
test('saves independent versions, serializes competing updates and hides foreign projects', async () => {
  const project = await fixture.db.project.create({ data: { ownerId: 'rec-owner', name: '추천' } });
  const repo = new ProfileRepository(fixture.db);
  expect(await repo.getDeveloper('rec-owner', project.id)).toBeNull();
  const created = await repo.putDeveloper('rec-owner', project.id, { expectedVersion: 0, data: developer });
  expect(created).toMatchObject({ version: 1, source: 'USER_DECLARED', data: developer });
  const competing = await Promise.allSettled([repo.putDeveloper('rec-owner', project.id, { expectedVersion: 1, data: { ...developer, role: 'FRONTEND' } }), repo.putDeveloper('rec-owner', project.id, { expectedVersion: 1, data: { ...developer, role: 'BACKEND' } })]);
  expect(competing.filter(v => v.status === 'fulfilled')).toHaveLength(1);
  expect(competing.find(v => v.status === 'rejected')).toMatchObject({ reason: { code: 'VERSION_CONFLICT' } });
  const env = await repo.putEnvironment('rec-owner', project.id, { expectedVersion: 0, data: environment });
  expect(env.version).toBe(1);
  expect(await repo.getBasis('rec-owner', project.id, 'snapshot-1')).toEqual({ projectVersion: 1, developerVersion: 2, environmentVersion: 1, catalogRevision: 'snapshot-1' });
  await expect(repo.getEnvironment('foreign', project.id)).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND' });
  await expect(repo.putDeveloper('foreign', project.id, { expectedVersion: 0, data: developer })).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND' });
});
