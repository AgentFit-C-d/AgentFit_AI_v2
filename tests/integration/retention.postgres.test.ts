let fixture: Awaited<ReturnType<typeof testDatabase>>;
beforeAll(async () => { fixture = await testDatabase(); }, 60000);
afterAll(async () => { if (fixture) await fixture.stop(); });
const key = 'ab'.repeat(32);
async function setup(label: string) {
  const db = fixture.db; const projects = new PrismaProjectRepository(db);
  await db.user.create({ data: { id: label, name: label, email: `${label}@example.invalid` } });
  const project = await projects.create(label, label); const store = new LocalInputStore(); const uploads = new PrismaUploadRepository(db);
  const service = new UploadService(store, uploads, async (owner, id) => !!await projects.findOwned(owner, id), async () => {});
  const grant = await service.createUpload(label, project.id, { kind: 'text', size: 19, contentType: 'text/plain' });
  await service.completeLocalUpload(label, project.id, grant.uploadId, new TextEncoder().encode('Backend: Express.js'));
  const attempts = new PrismaAttemptRepository(db);
  const queued = await attempts.start(label, project.id, grant.uploadId, 'nvidia', new Date());
  const attempt = (await attempts.claim(queued.id, new Date()))!;
  return { db, projects, project, store, uploads, grant, attempts, attempt, cleanup: new CleanupService(uploads, store), owner: label };
}
test('only received non-secret failure is encrypted separately and physically expires', async () => {
  const s = await setup('diagnostic'); const publish = vi.fn(async () => {}); const received = new Date();
  const diagnostics = new DiagnosticStore(s.db, key, publish);
  await diagnostics.saveFailureDiagnostic(s.attempt.id, s.attempt.leaseId!, null, received);
  await diagnostics.saveFailureDiagnostic(s.attempt.id, s.attempt.leaseId!, 'nvapi-' + 'a'.repeat(40), received);
  expect(await s.db.failureDiagnostic.count()).toBe(0);
  const raw = 'synthetic received invalid model response';
  await diagnostics.saveFailureDiagnostic(s.attempt.id, s.attempt.leaseId!, raw, received);
  const saved = await s.db.failureDiagnostic.findUniqueOrThrow({ where: { attemptId: s.attempt.id } });
  expect(Buffer.from(saved.ciphertext).toString()).not.toContain(raw);
  const decrypt = createDecipheriv('aes-256-gcm', Buffer.from(key, 'hex'), saved.iv);
  decrypt.setAAD(Buffer.from(s.attempt.id)); decrypt.setAuthTag(saved.authTag);
  expect(Buffer.concat([decrypt.update(saved.ciphertext), decrypt.final()]).toString()).toBe(raw);
  const outbox = await s.db.jobOutbox.findFirstOrThrow({ where: { kind: 'purge', targetId: saved.id } });
  expect(outbox.dueAt.getTime()).toBe(received.getTime() + 7 * 86400000 - 600000);
  expect(JSON.stringify(await s.projects.findOwned(s.owner, s.project.id))).not.toContain(raw);
  await diagnostics.expireDiagnostic(saved.id, outbox.dueAt);
  expect(await s.db.failureDiagnostic.count()).toBe(0);
  await s.attempts.finish(s.attempt.id, s.attempt.leaseId!, analysisResult(s.attempt.id), new Date());
  await diagnostics.saveFailureDiagnostic(s.attempt.id, s.attempt.leaseId!, raw, new Date());
  expect(await s.db.failureDiagnostic.count()).toBe(0);
  s.store.dispose();
});
test('failed deletion invalidates work, refuses success and supports durable retry then cascade', async () => {
  const s = await setup('deletion');
  const diagnostics = new DiagnosticStore(s.db, key, async () => {});
  await diagnostics.saveFailureDiagnostic(s.attempt.id, s.attempt.leaseId!, 'synthetic received failure', new Date());
  let fail = true; const cleanup = new CleanupService(s.uploads, s.store);
  const deleteRaw = s.store.delete.bind(s.store);
  s.store.delete = async ref => { if (fail) throw new Error('storage unavailable'); await deleteRaw(ref); };
  const deletion = new DeleteProjectService(s.db, cleanup, async () => {});
  await expect(deletion.deleteProject('foreign', s.project.id, { confirmation: true })).rejects.toMatchObject({ code: 'PROJECT_NOT_FOUND' });
  await expect(deletion.deleteProject(s.owner, s.project.id, { confirmation: false })).rejects.toThrow();
  await expect(deletion.deleteProject(s.owner, s.project.id, { confirmation: true })).rejects.toMatchObject({ code: 'DELETE_INCOMPLETE' });
  expect((await s.db.project.findUniqueOrThrow({ where: { id: s.project.id } })).deletingAt).not.toBeNull();
  expect(await s.attempts.finish(s.attempt.id, s.attempt.leaseId!, analysisResult(s.attempt.id), new Date())).toBe(false);
  expect(await s.db.jobOutbox.count({ where: { kind: 'delete', targetId: s.project.id, completedAt: null } })).toBe(1);
  fail = false; await deletion.resumeDelete(s.project.id);
  expect(await s.db.project.findUnique({ where: { id: s.project.id } })).toBeNull();
  expect(await s.db.analysisAttempt.count({ where: { projectId: s.project.id } })).toBe(0);
  expect(await s.db.failureDiagnostic.count({ where: { attemptId: s.attempt.id } })).toBe(0);
  expect(await s.db.upload.findUnique({ where: { id: s.grant.uploadId } })).toBeNull();
  await expect(s.store.read(s.grant)).rejects.toThrow('INPUT_UNAVAILABLE');
  await deletion.resumeDelete(s.project.id);
  s.store.dispose();
});

test('user upload quota remains atomic across projects and counts ready input', async () => {
  const db = fixture.db; const owner = 'upload-quota';
  await db.user.create({ data: { id: owner, name: owner, email: `${owner}@example.invalid` } });
  const projects = new PrismaProjectRepository(db); const uploads = new PrismaUploadRepository(db); const store = new LocalInputStore();
  const targets = await Promise.all(Array.from({ length: 6 }, (_, index) => projects.create(owner, `Quota ${index}`)));
  const records = targets.map(project => ({ ref: store.allocate({ kind: 'text', size: 5, contentType: 'text/plain' }), metadata: { kind: 'text' as const, size: 5, contentType: 'text/plain' }, ownerId: owner, projectId: project.id, state: 'READY' as const }));
  const results = await Promise.allSettled(records.map(record => uploads.createAndSchedule(record)));
  expect(results.filter(result => result.status === 'fulfilled')).toHaveLength(5);
  expect(results.find(result => result.status === 'rejected')).toMatchObject({ reason: { code: 'UPLOAD_LIMIT' } });
  store.dispose();
});
