import { expect, test } from '@playwright/test';
import { emptyProfile } from '../../packages/contracts/src';
test.beforeEach(async ({ context }) => { await context.addCookies([{ name: 'better-auth.session_token', value: process.env.E2E_SESSION_COOKIE!, url: 'http://localhost:3011' }]); });

test('non-React backend work offers optional debugging, TDD and verification Skills without a React recommendation', async ({ page }) => {
  const headers = { Origin: 'http://localhost:3011' };
  const response = await page.request.post('/api/projects', { headers, data: { name: '백엔드 공통 지침 검증' } }); expect(response.status()).toBe(201);
  const value = await response.json(); const path = `/api/projects/${value.id}`;
  expect((await page.request.patch(path + '/profile', { headers, data: { expectedVersion: 1, profile: { ...emptyProfile(), backend: ['FastAPI'], features: ['계정 API'] } } })).status()).toBe(200);
  expect((await page.request.put(path + '/developer-profile', { headers, data: { expectedVersion: 0, data: { role: 'BACKEND', responsibilities: ['API 구현', '테스트'], experienceLevel: null } } })).status()).toBe(201);
  expect((await page.request.put(path + '/environment-profile', { headers, data: { expectedVersion: 0, data: { os: { family: 'WINDOWS', version: '11' }, client: { id: 'codex-desktop', version: null }, runtimes: [], installedComponents: [], configurationKnowledge: 'UNKNOWN', authenticationReadiness: [] } } })).status()).toBe(201);
  expect((await page.request.post(path + '/recommendations', { headers, data: { expectedVersions: { project: 2, developer: 1, environment: 1 } } })).status()).toBe(201);
  await page.goto(`/projects/${value.id}`);
  await expect(page.getByRole('checkbox', { name: 'vercel-react-best-practices 선택' })).toHaveCount(0);
  await expect(page.getByRole('checkbox', { name: 'Superpowers 라이브러리 선택' })).not.toBeChecked();
  for (const name of ['writing-plans', 'systematic-debugging', 'test-driven-development', 'verification-before-completion']) await expect(page.getByRole('checkbox', { name: `${name} 선택` })).toHaveCount(0);
  await page.getByRole('checkbox', { name: 'Superpowers 라이브러리 선택' }).check();
  const result = page.waitForResponse(response => response.url().endsWith('/config-previews') && response.status() === 201);
  await page.getByRole('button', { name: '설정 미리보기 만들기' }).click();
  const preview = (await (await result).json()).preview;
  expect(preview.files.map((file: { relativePath: string }) => file.relativePath)).toEqual(['AGENTFIT-APPLY.md', 'AGENTFIT-SOURCES.md']);
  expect(preview.selectedToolIds).toEqual(['obra-systematic-debugging', 'obra-test-driven-development', 'obra-verification-before-completion', 'obra-writing-plans']);
  await page.getByRole('button', { name: '설정 검토 취소' }).click();
});
